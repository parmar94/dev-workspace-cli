package devcontainer

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"slices"

	"go.yaml.in/yaml/v3"
)

// StateFile records the selections used to generate the container so later
// commands (update, rebuild) can re-render without asking again.
var StateFile = path.Join(Dir, "dws.yaml")

// State is the content of StateFile.
type State struct {
	Version   int      `yaml:"version"`
	Name      string   `yaml:"name"`
	Template  string   `yaml:"template,omitempty"`
	BaseImage string   `yaml:"base_image"`
	User      string   `yaml:"remote_user"`
	Languages []string `yaml:"languages,omitempty"`
	Agents    []string `yaml:"agents,omitempty"`
	Tools     []string `yaml:"tools,omitempty"`
	SSH       SSHMode  `yaml:"ssh_agent,omitempty"`
	GitConfig bool     `yaml:"git_config,omitempty"`
	// AgentGuard installs deny rules for the selected agents.
	AgentGuard bool `yaml:"agent_guard"`
	// AgentSandbox turns on Claude Code's Bash sandbox.
	AgentSandbox bool  `yaml:"agent_sandbox,omitempty"`
	Ports        []int `yaml:"ports,omitempty"`
	// Generated maps each generated file (relative to the project root) to a
	// hash of its content, so dws update can detect hand edits.
	Generated map[string]string `yaml:"generated,omitempty"`
}

// Hash returns the content hash recorded in State.Generated.
func Hash(data []byte) string {
	sum := sha256.Sum256(data)
	return "sha256:" + hex.EncodeToString(sum[:])
}

// Record stores the hashes of files in s.Generated.
func (s *State) Record(files []File) {
	s.Generated = make(map[string]string, len(files))
	for _, f := range files {
		s.Generated[f.Path] = Hash(f.Data)
	}
}

// Modified returns the generated files under root whose content no longer
// matches the recorded hash, in sorted order. Deleted files count as
// modified.
func (s State) Modified(root string) []string {
	var out []string
	for p, want := range s.Generated {
		data, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(p)))
		if err != nil || Hash(data) != want {
			out = append(out, p)
		}
	}
	slices.Sort(out)
	return out
}

// File renders s as a File.
func (s State) File() (File, error) {
	var buf bytes.Buffer
	buf.WriteString("# Generated by dws. Records how this dev container was created.\n")
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(s); err != nil {
		return File{}, err
	}
	return File{Path: StateFile, Data: buf.Bytes()}, nil
}

// LoadState reads StateFile from the project at root.
func LoadState(root string) (State, error) {
	var s State
	data, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(StateFile)))
	if err != nil {
		return s, err
	}
	err = yaml.Unmarshal(data, &s)
	return s, err
}

// Write writes files under root. If root already has a .devcontainer
// directory it fails unless force is set, in which case the generated
// scripts and agent-policy directories are replaced and other files are
// overwritten.
func Write(root string, files []File, force bool) error {
	dir := filepath.Join(root, Dir)
	if _, err := os.Stat(dir); err == nil {
		if !force {
			return fmt.Errorf("%s already exists (use --force to overwrite)", dir)
		}
		for _, sub := range []string{"scripts", path.Base(policyDir)} {
			if err := os.RemoveAll(filepath.Join(dir, sub)); err != nil {
				return err
			}
		}
	} else if !errors.Is(err, fs.ErrNotExist) {
		return err
	}

	for _, f := range files {
		p := filepath.Join(root, filepath.FromSlash(f.Path))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			return err
		}
		mode := fs.FileMode(0o644)
		if f.Exec {
			mode = 0o755
		}
		if err := os.WriteFile(p, f.Data, mode); err != nil {
			return err
		}
		// WriteFile keeps the mode of an existing file; make sure it is right.
		if err := os.Chmod(p, mode); err != nil {
			return err
		}
	}
	return nil
}
